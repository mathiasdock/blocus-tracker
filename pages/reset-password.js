import { useState, useEffect, useRef } from "react";
import { useRouter } from "next/router";
import Link from "next/link";
import {
  clearInitialAuthCallback,
  createIsolatedAuthClient,
  getInitialAuthCallback,
  supabase,
} from "../lib/supabaseClient";
import {
  canAcceptRecoveryEvent,
  canUseEmailChangeSession,
} from "../lib/authRecovery.mjs";
import { useI18n } from "../contexts/I18nContext";
import AuthShell, { AuthHeading } from "../components/auth/AuthShell";
import { FieldGroup, FormNote, PasswordField } from "../components/auth/Field";
import MascotGuide from "../components/auth/MascotGuide";
import { guideText, setupGuide } from "../lib/setupGuide.mjs";

export default function ResetPassword() {
  const { t } = useI18n();
  const router = useRouter();

  const [ready, setReady]           = useState(false);
  const [invalid, setInvalid]       = useState(false);
  const [password, setPassword]     = useState("");
  const [confirm, setConfirm]       = useState("");
  const [busy, setBusy]             = useState(false);
  const [success, setSuccess]       = useState(false);
  const [err, setErr]               = useState("");
  const recoveryUserIdRef = useRef(null);
  const recoverySessionRef = useRef(null);

  useEffect(() => {
    if (!router.isReady) return;
    let active = true;
    let recoveryObserved = false;
    let initializationSucceeded = false;
    let callbackRejected = false;
    let settled = false;
    const callback = getInitialAuthCallback();

    const acceptRecovery = (session, event = "INITIAL_SESSION") => {
      if (!canAcceptRecoveryEvent({
        callback,
        session,
        event,
        initializationSucceeded,
        callbackRejected,
      })) return false;
      settled = true;
      recoveryObserved = true;
      recoveryUserIdRef.current = session.user.id;
      recoverySessionRef.current = {
        access_token: session.access_token,
        refresh_token: session.refresh_token,
      };
      setInvalid(false);
      setReady(true);
      return true;
    };

    const rejectCallback = () => {
      settled = true;
      callbackRejected = true;
      recoveryUserIdRef.current = null;
      recoverySessionRef.current = null;
      clearInitialAuthCallback();
      setReady(false);
      setInvalid(true);
    };

    // Filet de sécurité : initialize()/getSession() n'ont aucun timeout interne
    // (vérifié dans @supabase/auth-js), donc un réseau lent au moment précis où
    // quelqu'un ouvre son lien de réinitialisation peut laisser la page bloquée
    // sur le rond qui tourne indéfiniment. Avant, un simple setTimeout(8s)
    // garantissait un état "lien invalide, en redemander un" actionnable ;
    // perdu en réécrivant ce flux pour la protection anti-hijack de session.
    const timeoutTimer = setTimeout(() => {
      if (active && !settled) rejectCallback();
    }, 8000);

    const { data: { subscription } } = supabase.auth.onAuthStateChange((event, session) => {
      if (!active) return;
      if (acceptRecovery(session, event)) return;

      // Once a recovery session is accepted, never let a later sign-in from
      // this or another tab silently switch the account whose password changes.
      if (
        recoveryUserIdRef.current
        && session?.user?.id !== recoveryUserIdRef.current
      ) {
        rejectCallback();
      }
    });

    (async () => {
      try {
        // initialize() returns the result of the URL-token validation even when
        // the client started it before React mounted. Supabase intentionally
        // preserves an older session when that validation fails, so its error
        // must be checked before getSession().
        const { error: initializeError } = await supabase.auth.initialize();
        if (!active) return;
        if (initializeError || callback.errorCode || callback.hasPkceCode) {
          rejectCallback();
          return;
        }
        initializationSucceeded = true;

        const { data: { session }, error } = await supabase.auth.getSession();
        if (!active) return;

        // Compatibility for email-change links generated by the previously
        // deployed frontend, which redirected confirmations to this page.
        if (callback.isEmailChange) {
          if (!error && canUseEmailChangeSession(callback, session)) {
            clearInitialAuthCallback();
            await router.replace("/profile?email-change=confirmed");
          } else {
            rejectCallback();
          }
          return;
        }

        if (recoveryObserved) return;
        if (!error && acceptRecovery(session)) return;
        rejectCallback();
      } catch {
        if (active && !recoveryObserved) rejectCallback();
      }
    })();

    return () => {
      active = false;
      clearTimeout(timeoutTimer);
      subscription.unsubscribe();
    };
  }, [router, router.isReady]);

  const pwdMatch = confirm === "" || password === confirm;

  async function handleSubmit(e) {
    e.preventDefault();
    setErr("");

    if (password.length < 6) { setErr(t("signup.errPassword")); return; }
    if (password !== confirm) { setErr(t("auth.resetMismatch")); return; }

    setBusy(true);
    try {
      const expectedUserId = recoveryUserIdRef.current;
      const recoverySession = recoverySessionRef.current;
      if (!expectedUserId || !recoverySession?.access_token || !recoverySession?.refresh_token) {
        setBusy(false);
        recoveryUserIdRef.current = null;
        recoverySessionRef.current = null;
        clearInitialAuthCallback();
        setReady(false);
        setInvalid(true);
        return;
      }

      // Pin the mutation to the exact recovery tokens accepted above. The
      // shared client can be changed by another tab between two awaits; this
      // isolated in-memory client cannot silently switch to another account.
      const recoveryClient = createIsolatedAuthClient();
      const { data: pinnedData, error: pinError } = await recoveryClient.auth.setSession(
        recoverySession
      );
      if (pinError || pinnedData?.user?.id !== expectedUserId || !pinnedData?.session) {
        setBusy(false);
        recoveryUserIdRef.current = null;
        recoverySessionRef.current = null;
        clearInitialAuthCallback();
        setReady(false);
        setInvalid(true);
        return;
      }

      const { data: updateData, error } = await recoveryClient.auth.updateUser({ password });

      if (error || updateData?.user?.id !== expectedUserId) {
        setBusy(false);
        setErr(t("auth.resetError"));
      } else {
        // Keep this tab on the recovered account using the same pinned session.
        let nextPage = "/dashboard";
        try {
          const { error: syncError } = await supabase.auth.setSession({
            access_token: pinnedData.session.access_token,
            refresh_token: pinnedData.session.refresh_token,
          });
          if (syncError) nextPage = "/login";
        } catch {
          nextPage = "/login";
        }
        recoverySessionRef.current = null;
        clearInitialAuthCallback();
        setBusy(false);
        setSuccess(true);
        setTimeout(() => router.replace(nextPage), 2000);
      }
    } catch {
      setBusy(false);
      setErr(t("auth.resetError"));
    }
  }

  const alternate = { text: "", cta: t("auth.forgotBack"), href: "/login" };
  const guide = setupGuide({ page: "reset", invalid, success, checking: !invalid && !ready });
  const guideNode = <MascotGuide message={guideText(guide, t)} mood={guide.mood} reaction={guide.reaction} />;

  // Lien invalide / expiré
  if (invalid) {
    return (
      <AuthShell layout="single" alternate={alternate} guide={guideNode} contentKey="invalid">
        <AuthHeading title={t("auth.resetInvalidTitle")} lead={t("auth.resetInvalidLead")} />
        <Link href="/forgot-password" className="bt-auth-primary">{t("auth.resetRequestNew")}</Link>
      </AuthShell>
    );
  }

  // En attente de la session PASSWORD_RECOVERY
  if (!ready) {
    return (
      <AuthShell layout="single" alternate={alternate} guide={guideNode} contentKey="checking">
        <div className="bt-auth-skeleton" aria-busy="true">
          <span className="bt-skeleton" style={{ width: "62%", height: 30 }} />
          <span className="bt-skeleton bt-auth-skeleton-group is-short" />
          <span className="sr-only" role="status">{t("auth.resetChecking")}</span>
        </div>
      </AuthShell>
    );
  }

  if (success) {
    return (
      <AuthShell layout="single" guide={guideNode} contentKey="success">
        <AuthHeading title={t("auth.resetSuccessTitle")} />
      </AuthShell>
    );
  }

  return (
    <AuthShell layout="single" alternate={alternate} guide={guideNode} contentKey="form">
      <AuthHeading title={t("auth.resetTitle")} />
      <form onSubmit={handleSubmit} noValidate>
        <FieldGroup>
          <PasswordField
            id="reset-password"
            label={t("auth.resetNewPwd")}
            value={password}
            onChange={e => { setPassword(e.target.value); if (err) setErr(""); }}
            placeholder={t("setup.passwordPlaceholder")}
            autoComplete="new-password"
            autoFocus
            showLabel={t("auth.showPassword")}
            hideLabel={t("auth.hidePassword")}
          />
          <PasswordField
            id="reset-confirm"
            label={t("auth.resetConfirm")}
            value={confirm}
            onChange={e => { setConfirm(e.target.value); if (err) setErr(""); }}
            error={!pwdMatch ? t("auth.resetMismatch") : ""}
            autoComplete="new-password"
            showLabel={t("auth.showPassword")}
            hideLabel={t("auth.hidePassword")}
          />
        </FieldGroup>
        <FormNote tone="error">{err}</FormNote>
        <button className="bt-auth-primary" disabled={busy || password.length < 6 || password !== confirm} aria-busy={busy}>
          {busy && <span className="bt-button-spinner" aria-hidden="true" />}
          {busy ? t("auth.resetUpdating") : t("auth.resetBtn")}
        </button>
      </form>
    </AuthShell>
  );
}
